def make_pdf(path: Path, title: str, sections: list[tuple[str, list[str]]], page_break_each: bool = False) -> Path:
    regular, bold = fonts()
    h1 = ParagraphStyle("h1", fontName=bold, fontSize=18, leading=23, spaceAfter=8, textColor="#1f6f5c")
    h2 = ParagraphStyle("h2", fontName=bold, fontSize=13, leading=17, spaceBefore=8, spaceAfter=4)
    p = ParagraphStyle("p", fontName=regular, fontSize=11, leading=15, spaceAfter=5)
    note = ParagraphStyle("n", fontName=regular, fontSize=8, textColor="#b42318")
    story = [Paragraph(title, h1), Paragraph(DEMO_NOTE, note), Spacer(1, 4 * mm)]
    for i, (head, paras) in enumerate(sections):
        if page_break_each and i:
            story.append(PageBreak())
        story.append(Paragraph(head, h2))
        story += [Paragraph(x, p) for x in paras]
    SimpleDocTemplate(str(path), pagesize=A4, title=title, leftMargin=20 * mm, rightMargin=20 * mm).build(story)
    return path


