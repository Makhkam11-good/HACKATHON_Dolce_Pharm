    files = {
        "safety_pdf": make_pdf(out_dir / "Инструкция по охране труда для оператора.pdf",
                               "Инструкция по охране труда для оператора фасовочной линии", SAFETY_SECTIONS, page_break_each=True),
        "sop_docx": make_docx(out_dir / "СОП переодевание в чистой зоне.docx"),
        "ppe_xlsx": make_xlsx(out_dir / "Перечень СИЗ по участкам.xlsx"),
        "spill_pptx": make_pptx(out_dir / "Действия при разливе химических веществ.pptx"),
        "ppe_video": make_video(out_dir / "Видеоинструктаж СИЗ.mp4"),
    }
    for i, (title, _cat, _tags, sections) in enumerate(LIBRARY_DOCS):
        files[f"lib{i}"] = make_pdf(out_dir / f"lib_{i}.pdf", title, sections)
    return files
